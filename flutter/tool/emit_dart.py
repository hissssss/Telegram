def build_files(tokens_path: Path, groups_path: Path) -> dict[str, str]:
    tokens = json.loads(tokens_path.read_text(encoding="utf-8"))
    tokens_sha = sha256_file(tokens_path)
    groups_sha = sha256_file(groups_path)
    meta = tokens["meta"]

    head = header(tokens_sha, None, meta)
    head_groups = header(tokens_sha, groups_sha, meta)

    files: dict[str, str] = {
        "theme_keys.g.dart": emit_theme_keys(tokens, head),
        "theme_key_names.g.dart": emit_theme_key_names(tokens, head),
        "theme_fallbacks.g.dart": emit_theme_fallbacks(tokens, head),
        "palettes/default_colors.g.dart": emit_default_colors(tokens, head),
        "palettes/palettes.g.dart": emit_palettes_barrel(tokens, head),
        "color_scheme.g.dart": emit_color_scheme(tokens, groups_path, head_groups),
    }
    for theme_name in tokens["themes"]:
        snake, _ = theme_ident(theme_name)
        files[f"palettes/{snake}.g.dart"] = emit_theme_palette(tokens, theme_name, head)
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="regenerate to memory and byte-compare against the "
                             "committed files; exit 1 on drift")
    parser.add_argument("--tokens", type=Path, default=DEFAULT_TOKENS)
    parser.add_argument("--groups", type=Path, default=DEFAULT_GROUPS)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args(argv)

    files = build_files(args.tokens, args.groups)

    # Stale-file scan: only inside palettes/, the one directory this emitter
    # owns outright (a renamed upstream theme would otherwise leave a stale
    # overlay behind).  Sibling .g.dart files in tokens/ belong to other
    # generators (gen_shader_bindings.py, extract_spec.yaml emission).
    expected_paths = {args.out_dir / rel for rel in files}
    palettes_dir = args.out_dir / "palettes"
    stale = [
        p for p in palettes_dir.glob("*.g.dart")
        if p not in expected_paths
    ] if palettes_dir.exists() else []
    for p in stale:
        warn(f"stale generated file not in the emit set: {p}")

    if args.check:
        drift = []
        for rel, content in sorted(files.items()):
            path = args.out_dir / rel
            if not path.exists():
                drift.append(f"missing: {path}")
            elif path.read_bytes() != content.encode("utf-8"):
                drift.append(f"stale:   {path}")
        if drift or stale:
            for d in drift:
                print(f"emit_dart.py --check: {d}", file=sys.stderr)
            print(
                "emit_dart.py --check: drift detected; re-run "
                "python3 flutter/tool/emit_dart.py",
                file=sys.stderr,
            )
            return 1
        print(f"emit_dart.py --check: {len(files)} generated files are up to date")
        return 0

    for rel, content in sorted(files.items()):
        path = args.out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode("utf-8"))
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
