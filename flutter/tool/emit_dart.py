def load_groups(groups_path: Path) -> tuple[dict, list[str]]:
    with groups_path.open("rb") as fh:
        data = tomllib.load(fh)
    groups = data.get("groups", {})
    expected_ungrouped = data.get("ungrouped", {}).get("expected", [])
    for accessor, cfg in groups.items():
        if not is_identifier(accessor):
            raise EmitError(f"groups.toml: accessor {accessor!r} is not a valid identifier")
        if not is_identifier(cfg.get("class", "")):
            raise EmitError(f"groups.toml: group {accessor!r} has invalid class name")
        if not cfg.get("prefixes"):
            raise EmitError(f"groups.toml: group {accessor!r} has no prefixes")
    classes = [cfg["class"] for cfg in groups.values()]
    if len(set(classes)) != len(classes):
        raise EmitError("groups.toml: duplicate class names")
    return groups, expected_ungrouped


def assign_groups(keys: list[str], groups: dict) -> tuple[dict[str, list[tuple[str, str]]], list[str]]:
    """Returns ({accessor: [(member, key), ...]}, ungrouped_keys).

    Longest-prefix-wins matching; member = camelized remainder, falling back
    to the camelized full key name when the remainder is unusable.
    """
    by_prefix: list[tuple[str, str]] = []  # (prefix, accessor)
    for accessor, cfg in groups.items():
        for prefix in cfg["prefixes"]:
            by_prefix.append((prefix, accessor))
    by_prefix.sort(key=lambda pa: -len(pa[0]))

    assigned: dict[str, list[tuple[str, str]]] = {a: [] for a in groups}
    ungrouped: list[str] = []
    for key in keys:
        for prefix, accessor in by_prefix:
            if key.startswith(prefix):
                remainder = key[len(prefix):]
                member = camelize(remainder)
                if not is_identifier(member):
                    # Empty remainder, leading digit, or reserved word:
                    # fall back to the camelized full key name.
                    member = camelize(key)
                if not is_identifier(member):
                    raise EmitError(f"cannot derive member name for key {key!r}")
                assigned[accessor].append((member, key))
                break
        else:
            ungrouped.append(key)

    for accessor, members in assigned.items():
        seen: dict[str, str] = {}
        for member, key in members:
            if member in seen:
                raise EmitError(
                    f"group {accessor!r}: member {member!r} derived from both "
                    f"{seen[member]!r} and {key!r}"
                )
            seen[member] = key
    return assigned, ungrouped


def _wrap_arrow(head_part: str, call: str, arg: str) -> list[str]:
    """Replicates dart format's tall style for `head => call(arg);` members.

    1. one line if it fits;
    2. else break after `=>` (continuation indent +4) if the body fits;
    3. else block-split the argument list (args at +2, closing `);` at the
       member indent) — observed dart format 3.x behavior.
    """
    one = f"  {head_part} => {call}({arg});"
    if len(one) <= LINE_WIDTH:
        return [one]
    cont = f"      {call}({arg});"
    if len(cont) <= LINE_WIDTH:
        return [f"  {head_part} =>", cont]
    return [f"  {head_part} => {call}(", f"    {arg},", "  );"]


def _getter_lines(member: str, key: str, resolver: str) -> list[str]:
    return [f"  /// key_{key}"] + _wrap_arrow(
        f"Color get {member}", resolver, f"{KEYS_CLASS}.{key}"
    )


def emit_color_scheme(tokens: dict, groups_path: Path, head: str) -> str:
    keys = tokens["keys"]
    groups, expected_ungrouped = load_groups(groups_path)
    assigned, ungrouped = assign_groups(keys, groups)

    newly_ungrouped = [k for k in ungrouped if k not in set(expected_ungrouped)]
    if newly_ungrouped:
        warn(
            f"{len(newly_ungrouped)} key(s) fell into the UngroupedColors catch-all "
            f"but are not listed in groups.toml [ungrouped].expected: "
            + ", ".join(newly_ungrouped)
            + " — consider adding them to a group (or to the expected list)."
        )
    stale_expected = [k for k in expected_ungrouped if k not in set(ungrouped)]
    if stale_expected:
        warn(
            "groups.toml [ungrouped].expected lists keys that are no longer "
            "ungrouped (or no longer exist): " + ", ".join(stale_expected)
        )

    out = [head]
    out.append("import 'dart:ui' show Color;")
    out.append("")
    out.append("import 'theme_keys.g.dart';")
    out.append("")
    out.append("/// Resolves a [TelegramColorKey] ordinal into a themed [Color] (the")
    out.append("/// Theme.getColor analog supplied by the theme runtime).")
    out.append("typedef TelegramColorResolver = Color Function(int key);")
    out.append("")
    out.append("/// Typed accessor groups over the flat token space, generated from")
    out.append("/// flutter/tool/groups.toml. Example: `scheme.chat.inBubble` instead of")
    out.append(f"/// `resolve({KEYS_CLASS}.chat_inBubble)`. Keys outside every group are")
    out.append("/// reachable through [ungrouped] (and always through [resolve]).")
    out.append("class TelegramColorScheme {")
    out.append("  const TelegramColorScheme(this.resolve);")
    out.append("")
    out.append("  /// The underlying resolver — the full-key-space escape hatch.")
    out.append("  final TelegramColorResolver resolve;")
    for accessor, cfg in groups.items():
        out.append("")
        out.append(f"  /// {cfg['doc']}")
        out.extend(_wrap_arrow(f"{cfg['class']} get {accessor}", cfg["class"], "resolve"))
    out.append("")
    out.append("  /// Catch-all for keys not covered by any group in groups.toml.")
    out.append("  UngroupedColors get ungrouped => UngroupedColors(resolve);")
    out.append("}")

    for accessor, cfg in groups.items():
        out.append("")
        out.append(f"/// {cfg['doc']}")
        out.append(f"class {cfg['class']} {{")
        out.append(f"  const {cfg['class']}(this._resolve);")
        out.append("")
        out.append("  final TelegramColorResolver _resolve;")
        for member, key in assigned[accessor]:
            out.append("")
            out.extend(_getter_lines(member, key, "_resolve"))
        out.append("}")

    out.append("")
    out.append("/// Keys that match no prefix in groups.toml — the generation-stable")
    out.append("/// catch-all (new upstream keys land here before being grouped).")
    out.append("class UngroupedColors {")
    out.append("  const UngroupedColors(this._resolve);")
    out.append("")
    out.append("  final TelegramColorResolver _resolve;")
    seen: dict[str, str] = {}
    for key in ungrouped:
        member = camelize(key)
        if not is_identifier(member):
            raise EmitError(f"cannot derive ungrouped member name for {key!r}")
        if member in seen:
            raise EmitError(
                f"ungrouped member {member!r} derived from both {seen[member]!r} and {key!r}"
            )
        seen[member] = key
        out.append("")
        out.extend(_getter_lines(member, key, "_resolve"))
    out.append("}")
    return "\n".join(out) + "\n"


