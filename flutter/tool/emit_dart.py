def emit_theme_keys(tokens: dict, head: str) -> str:
    keys = tokens["keys"]
    out = [head]
    out.append("// ignore_for_file: constant_identifier_names")
    out.append("")
    out.append("/// Dense int color-key ordinals, identical to the `key_* = colorsCount++`")
    out.append("/// declaration order in Theme.java (each name below is the Java constant")
    out.append(f"/// minus its `key_` prefix). {len(keys)} keys.")
    out.append(f"abstract final class {KEYS_CLASS} {{")
    for i, key in enumerate(keys):
        if not is_identifier(key):
            raise EmitError(f"key {key!r} is not a valid Dart identifier")
        out.append(f"  static const int {key} = {i};")
    out.append("")
    out.append("  /// Theme.colorsCount — the size of every dense color table.")
    out.append(f"  static const int colorsCount = {len(keys)};")
    out.append("}")
    return "\n".join(out) + "\n"


def emit_theme_key_names(tokens: dict, head: str) -> str:
    keys = tokens["keys"]
    names = tokens["names"]
    out = [head]
    out.append("/// Serialized `.attheme` name -> key ordinal, ported verbatim from")
    out.append("/// ThemeColors.createColorKeysMap(). The string is NOT always the Java")
    out.append("/// identifier minus `key_` (e.g. listSelector -> 'listSelectorSDK21',")
    out.append("/// graySectionText -> 'key_graySectionText' upstream typo) — never derive")
    out.append("/// these names by string munging.")
    out.append("const Map<String, int> kAttThemeNames = <String, int>{")
    for i, key in enumerate(keys):
        if key in names:
            out.append(f"  '{names[key]}': {i},")
    out.append("};")
    out.append("")
    out.append("/// Key ordinal -> serialized `.attheme` name; null for the keys that have")
    out.append("/// no entry in createColorKeysMap() and therefore cannot appear in a")
    out.append("/// theme file.")
    out.append("const List<String?> kColorKeyNames = <String?>[")
    for key in keys:
        if key in names:
            out.append(f"  '{names[key]}',")
        else:
            out.append(f"  null, // {key}")
    out.append("];")
    return "\n".join(out) + "\n"


def emit_theme_fallbacks(tokens: dict, head: str) -> str:
    keys = tokens["keys"]
    ordinal = {k: i for i, k in enumerate(keys)}
    fallbacks = tokens["fallbacks"]
    forced = tokens["meta"]["forcedOpaqueKeys"]
    out = [head]
    out.append("/// Key -> fallback key (Theme.java `fallbackKeys` static table,")
    out.append(f"/// {len(fallbacks)} entries). Resolved at lookup time — currentColors[key] ??")
    out.append("/// currentColors[fallback[key]] ?? defaults[key] — never flattened, so")
    out.append("/// sparse overrides keep fallback behavior (ARCHITECTURE.md section 4.1).")
    out.append("const Map<int, int> kFallbackKeys = <int, int>{")
    for key in keys:
        if key in fallbacks:
            dst = fallbacks[key]
            line = f"  {ordinal[key]}: {ordinal[dst]}, // {key} -> {dst}"
            if len(line) <= LINE_WIDTH:
                out.append(line)
            else:
                # dartfmt counts trailing comments in line width and splits
                # long map entries after the ':' with +4 continuation indent.
                out.append(f"  {ordinal[key]}:")
                out.append(f"      {ordinal[dst]}, // {key} -> {dst}")
    out.append("};")
    out.append("")
    out.append("/// Keys whose resolved color is forced opaque (`color |= 0xFF000000`)")
    out.append("/// in Theme.getColor.")
    out.append("const List<int> kForcedOpaqueKeys = <int>[")
    for key in forced:
        out.append(f"  {ordinal[key]}, // {key}")
    out.append("];")
    return "\n".join(out) + "\n"


def emit_default_colors(tokens: dict, head: str) -> str:
    keys = tokens["keys"]
    defaults = tokens["defaults"]
    no_default = set(tokens["meta"]["keysWithoutDefault"])
    out = [head]
    out.append("/// ThemeColors.createDefaultColors() as a dense ARGB table of length")
    out.append(f"/// {KEYS_CLASS}.colorsCount. Keys with no upstream assignment are")
    out.append("/// 0x00000000, matching Java's zero-initialized array (they resolve via")
    out.append("/// kFallbackKeys or are runtime-computed, e.g. chat_serviceBackground).")
    out.append("const List<int> kDefaultColors = <int>[")
    for i, key in enumerate(keys):
        if key in defaults:
            out.append(f"  {defaults[key]}, // {i} {key}")
        else:
            assert key in no_default
            out.append(f"  0x00000000, // {i} {key} (no default upstream)")
    out.append("];")
    return "\n".join(out) + "\n"


def emit_theme_palette(tokens: dict, theme_name: str, head: str) -> str:
    keys = tokens["keys"]
    ordinal = {k: i for i, k in enumerate(keys)}
    overlay = tokens["themes"][theme_name]
    meta = tokens["meta"]["themes"][theme_name]
    _, const_name = theme_ident(theme_name)
    out = [head]
    out.append(f"/// Sparse color overlay for the bundled Android theme '{theme_name}'")
    out.append(f"/// ({meta['asset']}, {len(overlay)} entries), parsed with Android-exact")
    out.append("/// `.attheme` semantics. Keys not present resolve through kFallbackKeys")
    out.append("/// and then kDefaultColors. Ordinal 0 (wallpaperFileOffset) mirrors")
    out.append("/// Android's parser, which always stores the wallpaper byte offset")
    out.append("/// (-1 when the file has no WPS marker) — it is not a color.")
    if meta["droppedFinalLine"] is not None:
        out.append("///")
        out.append(f"/// Android parity note: the asset's final line has no trailing newline")
        out.append("/// and is silently dropped by Theme.getThemeFileValues — replicated here")
        out.append(f"/// (dropped: `{meta['droppedFinalLine']}`).")
    out.append(f"const Map<int, int> {const_name} = <int, int>{{")
    for key, value in overlay.items():
        out.append(f"  {ordinal[key]}: {value}, // {key}")
    out.append("};")
    return "\n".join(out) + "\n"


def emit_palettes_barrel(tokens: dict, head: str) -> str:
    theme_names = list(tokens["themes"])
    out = [head]
    for name in theme_names:
        snake, _ = theme_ident(name)
        out.append(f"import '{snake}.g.dart';")
    out.append("")
    out.append("export 'default_colors.g.dart';")
    for name in theme_names:
        snake, _ = theme_ident(name)
        out.append(f"export '{snake}.g.dart';")
    out.append("")
    out.append("/// Bundled sparse theme overlays keyed by their Android registration name")
    out.append("/// (Theme.java static init; 'Blue' is the default day theme and 'Dark Blue'")
    out.append("/// the default night theme).")
    out.append("const Map<String, Map<int, int>> kBundledThemes = <String, Map<int, int>>{")
    for name in theme_names:
        _, const_name = theme_ident(name)
        out.append(f"  '{name}': {const_name},")
    out.append("};")
    return "\n".join(out) + "\n"


