#!/usr/bin/env python3
"""emit_dart.py — Stages 2+3 of the telegram_ui token codegen pipeline.

Reads the checked-in `theme_tokens.json` intermediate (produced by
gen_tokens.py) plus the `groups.toml` prefix -> typed-group mapping and
emits the committed Dart token files into
`flutter/telegram_ui/lib/src/tokens/`:

  theme_keys.g.dart              777 const int ordinals (TelegramColorKey)
  theme_key_names.g.dart         attheme name <-> key maps
  theme_fallbacks.g.dart         fallback table + forced-opaque key list
  palettes/default_colors.g.dart kDefaultColors (dense, length colorsCount)
  palettes/theme_<name>.g.dart   per-bundled-theme sparse overlay maps
  palettes/palettes.g.dart       barrel + kBundledThemes registry
  color_scheme.g.dart            typed groups from groups.toml + catch-all

Output is byte-stable and dartfmt-clean by construction (the emitter writes
exactly what `dart format` would produce — verified by the package test
suite / CI running `dart format --set-exit-if-changed`).  Headers are
stamped with the SHA-256 of the inputs, so upstream churn shows up as
reviewable diffs.

Usage:
  python3 emit_dart.py           # (re)write the generated files
  python3 emit_dart.py --check   # regenerate to memory, byte-compare, exit 1 on drift
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import tomllib
from pathlib import Path

TOOL_DIR = Path(__file__).resolve().parent
DEFAULT_TOKENS = TOOL_DIR / "theme_tokens.json"
DEFAULT_GROUPS = TOOL_DIR / "groups.toml"
DEFAULT_OUT_DIR = TOOL_DIR.parent / "telegram_ui" / "lib" / "src" / "tokens"

LINE_WIDTH = 80
KEYS_CLASS = "TelegramColorKey"

# Words that cannot (or must not) be used as generated member names: Dart
# reserved words, built-in identifiers, and Object/API members of the
# generated classes.
RESERVED = {
    "assert", "break", "case", "catch", "class", "const", "continue",
    "default", "do", "else", "enum", "extends", "false", "final", "finally",
    "for", "if", "in", "is", "new", "null", "rethrow", "return", "super",
    "switch", "this", "throw", "true", "try", "var", "void", "while", "with",
    "abstract", "as", "covariant", "deferred", "dynamic", "export",
    "extension", "external", "factory", "get", "implements", "import",
    "interface", "late", "library", "mixin", "operator", "part", "required",
    "set", "static", "typedef", "await", "yield", "base", "sealed", "when",
    "hashCode", "runtimeType", "toString", "noSuchMethod", "resolve",
}


class EmitError(RuntimeError):
    pass


def warn(msg: str) -> None:
    print(f"emit_dart.py: warning: {msg}", file=sys.stderr)


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def is_identifier(name: str) -> bool:
    if not name or name in RESERVED:
        return False
    if not (name[0].isalpha() or name[0] in "_$"):
        return False
    return all(c.isalnum() or c in "_$" for c in name)


def camelize(name: str) -> str:
    """snake-ish -> lowerCamelCase: 'wallpaper_gradient_to1' -> 'wallpaperGradientTo1',
    'White' -> 'white'."""
    parts = [p for p in name.split("_") if p]
    if not parts:
        return ""
    first = parts[0][0].lower() + parts[0][1:]
    rest = [p[0].upper() + p[1:] for p in parts[1:]]
    return first + "".join(rest)


def theme_ident(theme_name: str) -> tuple[str, str]:
    """'Dark Blue' -> ('theme_dark_blue', 'kDarkBlueTheme')."""
    words = theme_name.split()
    snake = "_".join(w.lower() for w in words)
    pascal = "".join(w[0].upper() + w[1:].lower() for w in words)
    return f"theme_{snake}", f"k{pascal}Theme"


# ---------------------------------------------------------------------------
# Header
# ---------------------------------------------------------------------------


def header(tokens_sha: str, groups_sha: str | None, tokens_meta: dict) -> str:
    lines = [
        "// GENERATED CODE - DO NOT MODIFY BY HAND.",
        "//",
        "// Generated by flutter/tool/emit_dart.py from flutter/tool/theme_tokens.json",
        "// (token codegen pipeline stages 2-3, flutter/docs/ARCHITECTURE.md section 4.3).",
        "// Regenerate: python3 flutter/tool/gen_tokens.py && python3 flutter/tool/emit_dart.py",
        "// Drift gate:  both scripts support --check (byte-compare, nonzero exit).",
        "//",
        "// Inputs:",
        f"//   theme_tokens.json sha256: {tokens_sha}",
    ]
    if groups_sha is not None:
        lines.append(f"//   groups.toml       sha256: {groups_sha}")
    lines += [
        "// Upstream Java sources (paths + sha256 recorded in theme_tokens.json meta):",
    ]
    for label, src in tokens_meta["sources"].items():
        lines.append(f"//   {label}: {src['sha256']}")
    lines += [
        "//",
        "// Output is dartfmt-clean by construction: `dart format` must be a no-op",
        "// on this file (enforced in CI with `dart format --set-exit-if-changed`).",
        "",
    ]
    return "\n".join(lines)


